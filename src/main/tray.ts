// Note: clicking the tray icon moves focus to the Windows shell (that is how
// the notification area works), so while driving use the global shortcuts
// (settings.shortcuts) instead of the menu.

/** Windows truncates tray tooltips at 127 characters. */
const TOOLTIP_MAX = 127

/** Tray art by taskbar theme ('dark': light glyph for a dark taskbar) and display scale. */
export const TRAY_ICONS = {
  dark: { 1: darkIcon16, 1.25: darkIcon20, 1.5: darkIcon24, 2: darkIcon32 },
  light: { 1: lightIcon16, 1.25: lightIcon20, 1.5: lightIcon24, 2: lightIcon32 }
} as const satisfies Record<'dark' | 'light', Record<number, string>>

export type TaskbarTheme = keyof typeof TRAY_ICONS

export interface TrayState {
  status: OverlayStatus
  settings: OverlaySettings
  editMode: boolean
  /** The user hid every overlay window (this checkbox, the shortcut). */
  overlayHidden: boolean
  /** Why each widget a visibility rule hides right now is hidden (null: no known reason). */
  autoHidden: Partial<Record<WidgetId, HiddenReason | null>>
  /** The car model you are in now (null: none), to mark the layout linked to it. */
  carId?: number | null
}

export interface TrayActions {
  /** The settings window, on `page` when given. */
  openSettings(page?: SettingsWindowPage): void
  /** Makes a saved layout the one in use (settings.savedLayouts). */
  applyLayout(id: string): void
  setWidgetVisible(id: WidgetId, visible: boolean): void
  setRadarRange(rangeM: number): void
  /** When the overlay is shown (settings.visibility.showWhen). */
  setShowWhen(showWhen: ShowWhen): void
  setEditMode(on: boolean): void
  setOverlayHidden(hidden: boolean): void
  openSettingsFolder(): void
  quit(): void
}

// Module-level so the Tray is never garbage collected (the icon would vanish).
let tray: Tray | null = null
let actions: TrayActions | null = null
let lastKey = ''
/** The taskbar theme the current icon was drawn for. */
let iconTheme: TaskbarTheme | null = null

export function createTray(state: TrayState, trayActions: TrayActions): void {
  if (tray) return
  actions = trayActions
  iconTheme = taskbarTheme()
  tray = new Tray(loadIcon(iconTheme))
  // Left click opens the same menu as right click.
  tray.on('click', () => tray?.popUpContextMenu())
  nativeTheme.on('updated', onThemeUpdated)
  updateTray(state)
}

/** Windows switched between a light and a dark taskbar: redraw the icon for it. */
function onThemeUpdated(): void {
  if (!tray || tray.isDestroyed()) return
  const theme = taskbarTheme()
  if (theme === iconTheme) return
  iconTheme = theme
  tray.setImage(loadIcon(theme))
}

/** The taskbar's theme, which is not always the apps' (Windows sets them separately). */
export function taskbarTheme(): TaskbarTheme {
  return nativeTheme.shouldUseDarkColorsForSystemIntegratedUI ? 'dark' : 'light'
}

/**
 * Rebuilds the tooltip and menu from the current state, in the interface
 * language (skipped when nothing changed: switching language rebuilds them).
 */
export function updateTray(state: TrayState): void {
  if (!tray || tray.isDestroyed() || !actions) return
  const lang = state.settings.appearance.language
  const status = statusText(messagesFor(lang), state.status)
  const key = JSON.stringify([
    lang,
    status,
    state.editMode,
    state.overlayHidden,
    state.settings.shortcuts,
    state.settings.radar.rangeM,
    state.settings.visibility.showWhen,
    layoutsKey(state),
    // '' shown, '-' hidden for no known reason (JSON would turn both undefined and null into null).
    WIDGET_IDS.map((id) => [state.settings.widgets[id].visible, hiddenKey(state.autoHidden[id])])
  ])
  if (key === lastKey) return
  lastKey = key
  const msg = messagesFor(lang)
  const t = msg.core.tray
  const common = commonHiddenReason(state)
  const tooltip = state.overlayHidden
    ? t.tooltipHidden(status)
    : common !== undefined
      ? t.tooltipAutoHidden(status, hiddenText(msg, common))
      : t.tooltip(status)
  tray.setToolTip(tooltip.slice(0, TOOLTIP_MAX))
  tray.setContextMenu(Menu.buildFromTemplate(buildMenu(state, status, actions)))
}

/** Most layouts the submenu lists; past it, "Más…" opens the settings window's page. */
export const TRAY_LAYOUTS = 5

/** What the layouts submenu shows: which ones, names, order, the one in use, the car's. */
function layoutsKey(state: TrayState): unknown {
  const lib = state.settings.savedLayouts
  return [
    lib.activeId,
    trayLayouts(state).map((l) => [l.id, l.name]),
    lib.list.length > TRAY_LAYOUTS,
    currentCarLayout(state)
  ]
}

/** The layouts the submenu lists (recentLayouts: the one in use and the car's among them). */
function trayLayouts(state: TrayState): ReturnType<typeof recentLayouts> {
  return recentLayouts(state.settings.savedLayouts, TRAY_LAYOUTS, currentCarLayout(state))
}

/** The layout linked to the car you are in, while the automatic mode is on (null: none). */
function currentCarLayout(state: TrayState): string | null {
  const carId = state.carId ?? null
  if (carId === null || !state.settings.layouts.autoSwitch) return null
  return linkedLayoutId(state.settings.savedLayouts, carId)
}

/**
 * The layouts submenu: one radio item per saved layout, in the user's order (the one in use
 * checked; the one linked to the car you are in marked), then "Gestionar disposiciones…" (the
 * settings window's page). Past TRAY_LAYOUTS, only the one in use, the car's and the latest used
 * ones (recentLayouts' order), then "Más…" in its place: one entry to that page, where the rest are.
 */
export function layoutsMenu(state: TrayState, act: TrayActions): MenuItemConstructorOptions[] {
  const lib = state.settings.savedLayouts
  const t = messagesFor(state.settings.appearance.language).core.tray
  const carLayout = currentCarLayout(state)
  const more = lib.list.length > TRAY_LAYOUTS
  return [
    ...trayLayouts(state).map((l): MenuItemConstructorOptions => ({
      label: l.id === carLayout ? t.layoutForCar(l.name) : l.name,
      type: 'radio',
      checked: l.id === lib.activeId,
      click: () => act.applyLayout(l.id)
    })),
    { type: 'separator' },
    {
      label: more ? t.moreLayouts : t.manageLayouts,
      click: () => act.openSettings('layouts')
    }
  ]
}

function hiddenKey(hidden: HiddenReason | null | undefined): string {
  return hidden === undefined ? '' : (hidden ?? '-')
}

/**
 * The one reason a rule hides every enabled widget right now for ('out-of-car' out of the car,
 * 'garage'...), undefined when one is shown, they differ, none is enabled or the reason is not
 * known: the tooltip and the menu say it once instead of on every widget.
 */
export function commonHiddenReason(
  state: Pick<TrayState, 'settings' | 'autoHidden'>
): HiddenReason | undefined {
  let common: HiddenReason | undefined
  for (const id of WIDGET_IDS) {
    if (!state.settings.widgets[id].visible) continue
    const reason = state.autoHidden[id]
    if (reason === undefined || reason === null) return undefined
    if (common !== undefined && reason !== common) return undefined
    common = reason
  }
  return common
}

export function destroyTray(): void {
  nativeTheme.removeListener('updated', onThemeUpdated)
  if (tray && !tray.isDestroyed()) tray.destroy()
  tray = null
  actions = null
  lastKey = ''
  iconTheme = null
}

function buildMenu(
  state: TrayState,
  status: string,
  act: TrayActions
): MenuItemConstructorOptions[] {
  const { settings } = state
  const { shortcuts } = settings
  const lang = settings.appearance.language
  const msg = messagesFor(lang)
  const t = msg.core.tray
  const rangeM = settings.radar.rangeM
  const showWhen = settings.visibility.showWhen
  // Said once, under the status, while it hides every enabled widget.
  const common = commonHiddenReason(state)
  const ranges: number[] = [...RADAR_RANGE_PRESETS_M]
  // A value edited by hand in settings.json still shows up as the checked choice.
  if (!ranges.includes(rangeM)) ranges.push(rangeM)
  ranges.sort((a, b) => a - b)

  return [
    { label: status, enabled: false },
    ...(common === undefined
      ? []
      : [{ label: hiddenText(msg, common), enabled: false } satisfies MenuItemConstructorOptions]),
    { type: 'separator' },
    { label: t.settings, click: () => act.openSettings() },
    { type: 'separator' },
    // The checkbox is what the user enabled; a rule hiding the widget right now only adds a note
    // (none when the line under the status already says why they all are).
    ...WIDGET_IDS.map((id): MenuItemConstructorOptions => ({
      label: widgetLabel(
        lang,
        id,
        settings.widgets[id].visible && common === undefined ? state.autoHidden[id] : undefined
      ),
      type: 'checkbox',
      checked: settings.widgets[id].visible,
      click: (item) => act.setWidgetVisible(id, item.checked)
    })),
    {
      label: t.radarRange,
      submenu: ranges.map((m): MenuItemConstructorOptions => ({
        label: t.rangeMeters(m),
        type: 'radio',
        checked: m === rangeM,
        click: () => act.setRadarRange(m)
      }))
    },
    {
      label: t.showWhen,
      submenu: SHOW_WHEN.map((value): MenuItemConstructorOptions => ({
        label: msg.core.showWhen[value],
        type: 'radio',
        checked: value === showWhen,
        click: () => act.setShowWhen(value)
      }))
    },
    { label: t.layouts, submenu: layoutsMenu(state, act) },
    { type: 'separator' },
    {
      label: t.hideOverlay,
      type: 'checkbox',
      checked: state.overlayHidden,
      ...acceleratorLabel(shortcuts.toggleOverlay),
      click: (item) => act.setOverlayHidden(item.checked)
    },
    {
      label: t.editMode,
      type: 'checkbox',
      checked: state.editMode,
      ...acceleratorLabel(shortcuts.toggleEditMode),
      click: (item) => act.setEditMode(item.checked)
    },
    { label: t.openSettingsFolder, click: () => act.openSettingsFolder() },
    { type: 'separator' },
    { label: t.quit, click: () => act.quit() }
  ]
}

/**
 * A configured shortcut, shown next to its item. Only the label: the real shortcut is a
 * globalShortcut registered by main (shortcutManager.ts). None when it is turned off ('').
 */
function acceleratorLabel(
  accelerator: string
): Pick<MenuItemConstructorOptions, 'accelerator' | 'registerAccelerator'> {
  return accelerator === '' ? {} : { accelerator, registerAccelerator: false }
}

/**
 * 'Batalla', or 'Batalla (oculto en práctica)' while a rule hides it
 * (`hidden`: undefined when shown, null when hidden for no known reason).
 */
export function widgetLabel(
  lang: Language,
  id: WidgetId,
  hidden: HiddenReason | null | undefined
): string {
  const m = messagesFor(lang)
  const title = widgetTitle(m, id)
  if (hidden === undefined) return title
  const caption = hiddenText(m, hidden)
  const note = caption.charAt(0).toLocaleLowerCase(LOCALES[lang]) + caption.slice(1)
  return m.core.tray.widgetHidden(title, note)
}

/**
 * One image with the art for every display scale (16 px at 100 %, 20 at 125 %,
 * 24 at 150 %, 32 at 200 %): Windows picks the one for the tray's scale
 * instead of resampling, so the small sizes keep their hand-placed pixels.
 */
export function loadIcon(theme: TaskbarTheme): NativeImage {
  const icon = nativeImage.createEmpty()
  // Object keys list 1 and 2 before 1.25 and 1.5: sort, the smallest art first.
  const sizes = Object.entries(TRAY_ICONS[theme]).sort(([a], [b]) => Number(a) - Number(b))
  for (const [scale, file] of sizes) {
    const art = nativeImage.createFromPath(file)
    if (art.isEmpty()) {
      console.warn(`[tray] icon not found at ${file}`)
      continue
    }
    icon.addRepresentation({ scaleFactor: Number(scale), buffer: art.toPNG() })
  }
  return icon
}
