// Regenerates src/renderer/src/ui/brandLogoSizes.ts (npm run logo-sizes): the scale BrandMark
// draws each make's logo at, so every logo reads at about the same size in a row. Plain Node,
// no browser: the logo data and the measuring code are TypeScript Node runs as is (type
// stripping). The tests measure again and fail when this file is stale or misses a logo.
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import * as prettier from 'prettier'

const ROOT = path.resolve(import.meta.dirname, '..')
const UI = path.join(ROOT, 'src', 'renderer', 'src', 'ui')
const OUT = path.join(UI, 'brandLogoSizes.ts')
const load = (file) => import(pathToFileURL(path.join(UI, file)).href)

const { COLOR_LOGOS } = await load('brandLogosColor.ts')
const { BRAND_LOGOS } = await load('brandLogos.ts')
const { fitLogo, measureInk } = await load('brandLogoInk.ts')

const fits = {
  color: Object.entries(COLOR_LOGOS).map(([id, l]) => [
    id,
    fitLogo(l.viewBox, measureInk(l.layers))
  ]),
  mono: Object.entries(BRAND_LOGOS).map(([id, l]) => [
    id,
    fitLogo(l.viewBox, measureInk([{ d: l.d }]))
  ])
}

const entries = (list) => list.map(([id, f]) => `  ${JSON.stringify(id)}: ${f.scale},`).join('\n')
const source = `// Generated by scripts/brand-logo-sizes.mjs (npm run logo-sizes) from the logos' path data.
// Do not edit by hand: change the rule in brandLogoInk.ts or a logo, and run the script again.
import type { KnownBrandId } from '@shared/carBrands'

/**
 * The height BrandMark draws each logo at, in heights of its slot (1 = as tall as the slot,
 * 85 % of the plate), so every logo reads at about the same size: see fitLogo in
 * brandLogoInk.ts. COLOR is for the colour logos (and their greys in monochrome), MONO for the
 * Simple Icons paths.
 */
export const LOGO_SCALE_COLOR: Readonly<Partial<Record<KnownBrandId, number>>> = {
${entries(fits.color)}
}

export const LOGO_SCALE_MONO: Readonly<Partial<Record<KnownBrandId, number>>> = {
${entries(fits.mono)}
}
`
const options = { ...(await prettier.resolveConfig(OUT)), filepath: OUT }
fs.writeFileSync(OUT, await prettier.format(source, options))

const pct = (v) => `${Math.round(v * 100)}%`
for (const [set, list] of Object.entries(fits)) {
  console.log(`\n${set}: logo, scale, apparent size before -> after (slot heights)`)
  for (const [id, f] of list) {
    console.log(`  ${id.padEnd(14)} ${f.scale.toFixed(2)}  ${pct(f.before)} -> ${pct(f.after)}`)
  }
  const spread = (k) =>
    Math.max(...list.map(([, f]) => f[k])) / Math.min(...list.map(([, f]) => f[k]))
  console.log(
    `  largest / smallest: ${spread('before').toFixed(2)} -> ${spread('after').toFixed(2)}`
  )
}
console.log(`\nwrote ${path.relative(ROOT, OUT)}`)
